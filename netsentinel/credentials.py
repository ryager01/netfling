def lookup_default_credentials(
    vendor: str,
    hostname: str = "",
    device_type: str = "",
    ip: str = "192.168.1.1",
) -> Optional[Dict[str, Any]]:
    """
    Looks up known factory default credentials and admin web pages for a device.
    Matches across vendor name, hostname, and device type.
    """
    search_haystack = f"{vendor} {hostname} {device_type}".lower()

    for item in DEFAULT_CREDENTIALS_REGISTRY:
        for pat in item["patterns"]:
            if pat in search_haystack:
                admin_link = item["admin_url"].format(ip=ip)
                rtsp_link = item.get("rtsp_url", "").format(ip=ip) if item.get("rtsp_url") else None
                return {
                    "has_defaults": True,
                    "default_username": item["username"],
                    "default_password": item["password"],
                    "alt_password": item.get("alt_password"),
                    "admin_url": admin_link,
                    "rtsp_url": rtsp_link,
                    "onvif_port": item.get("onvif_port"),
                    "default_web_host": item.get("default_web"),
                    "notes": item["notes"],
                    "protocol": item["protocol"],
                    "port": item["port"],
                }

    # If it's a generic router or gateway, provide common router fallback credentials
    if "router" in device_type.lower() or "gateway" in device_type.lower() or ip.endswith(".1"):
        return {
            "has_defaults": True,
            "default_username": "admin",
            "default_password": "admin (or 'password')",
            "admin_url": f"http://{ip}",
            "notes": "Generic residential gateway default. Typically admin/admin or admin/password.",
            "protocol": "HTTP",
            "port": 80,
        }

    return None
