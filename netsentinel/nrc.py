"""
Network Relationship Canvas (NRC) Engine & Firewall Translation Compiler.
Translates visual topology relationships into platform-native firewall rules,
evaluates compliance, and provides natural-language AI policy translation.
"""

import json
import re
from typing import Any, Dict, List, Optional, Tuple


class FirewallRuleCompiler:
    """
    Compiles declared canvas intent into concrete, platform-native firewall rules.
    Supported Providers:
      - Windows Defender Firewall (netsh advfirewall)
      - Linux nftables (nft)
      - Linux iptables (iptables-legacy / iptables-nft)
      - Ubuntu/Debian ufw
      - BSD / macOS / pfSense / OPNsense pf (packet filter)
    """

    @staticmethod
    def compile_topology(
        topology: Dict[str, Any],
        provider: str = "windows_firewall",
        target_node_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Compiles all relationships in the topology into concrete rules for the specified provider.
        If target_node_id is provided, only rules affecting that specific host are generated.
        """
        nodes_by_id = {n["id"]: n for n in topology.get("nodes", [])}
        groups_by_id = {g["id"]: g for g in topology.get("groups", [])}
        relationships = topology.get("relationships", [])

        # Group membership resolution: group_id -> list of node dicts
        group_members: Dict[str, List[Dict[str, Any]]] = {}
        for n in topology.get("nodes", []):
            gid = n.get("group_id")
            if gid:
                if gid not in group_members:
                    group_members[gid] = []
                group_members[gid].append(n)

        compiled_rules: List[Dict[str, Any]] = []
        raw_script_lines: List[str] = []

        # Platform header comment
        raw_script_lines.append(f"# NetSentinel NRC Firewall Configuration")
        raw_script_lines.append(f"# Target Provider: {provider.upper()}")
        raw_script_lines.append(f"# Generated by Network Relationship Canvas Intent Compiler")
        raw_script_lines.append(f"# Default Security Posture: STRICT DEFAULT DENY")
        raw_script_lines.append("")

        # 1. Base Default Deny Policy Syntax
        if provider == "windows_firewall":
            raw_script_lines.append("rem --- Baseline Default Inbound Block ---")
            raw_script_lines.append("netsh advfirewall set allprofiles firewallpolicy blockinbound,allowoutbound")
            raw_script_lines.append("")
        elif provider == "nftables":
            raw_script_lines.append("# --- Baseline nftables table & chain setup ---")
            raw_script_lines.append("nft add table inet nrc_filter")
            raw_script_lines.append("nft add chain inet nrc_filter input { type filter hook input priority 0 \\; policy drop \\; }")
            raw_script_lines.append("nft add chain inet nrc_filter forward { type filter hook forward priority 0 \\; policy drop \\; }")
            raw_script_lines.append("nft add rule inet nrc_filter input ct state established,related accept")
            raw_script_lines.append("nft add rule inet nrc_filter input iifname \"lo\" accept")
            raw_script_lines.append("")
        elif provider == "iptables":
            raw_script_lines.append("# --- Baseline iptables drop policies ---")
            raw_script_lines.append("iptables -F")
            raw_script_lines.append("iptables -P INPUT DROP")
            raw_script_lines.append("iptables -P FORWARD DROP")
            raw_script_lines.append("iptables -A INPUT -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT")
            raw_script_lines.append("iptables -A INPUT -i lo -j ACCEPT")
            raw_script_lines.append("")
        elif provider == "ufw":
            raw_script_lines.append("# --- Baseline ufw defaults ---")
            raw_script_lines.append("ufw default deny incoming")
            raw_script_lines.append("ufw default allow outgoing")
            raw_script_lines.append("")
        elif provider in ["pf", "pfsense", "opnsense"]:
            raw_script_lines.append("# --- Baseline pf packet filter macros & drop policy ---")
            raw_script_lines.append("set skip on lo0")
            raw_script_lines.append("block in log all")
            raw_script_lines.append("pass out quick all keep state")
            raw_script_lines.append("")

        # 2. Iterate each relationship and synthesize rules
        rule_seq = 1
        for rel in relationships:
            src_id = rel.get("source_node_id")
            tgt_id = rel.get("target_node_id")

            # Resolve actual source and target entities (could be node or group)
            sources: List[Dict[str, Any]] = []
            targets: List[Dict[str, Any]] = []

            if src_id in nodes_by_id:
                sources.append(nodes_by_id[src_id])
            elif src_id in group_members:
                sources.extend(group_members[src_id])

            if tgt_id in nodes_by_id:
                targets.append(nodes_by_id[tgt_id])
            elif tgt_id in group_members:
                targets.extend(group_members[tgt_id])

            if not sources or not targets:
                continue

            direction = rel.get("direction", "one_way")
            protocol = rel.get("protocol", "tcp").lower()
            allowed_ports = rel.get("allowed_ports", ["443"])
            triggered_ports = rel.get("triggered_ports", [])
            stateful = bool(rel.get("is_stateful", True))
            logging = bool(rel.get("logging_enabled", True))
            notes = rel.get("ai_notes", "")

            # Filter if target_node_id is specified
            for src in sources:
                for tgt in targets:
                    if target_node_id and (src["id"] != target_node_id and tgt["id"] != target_node_id):
                        continue

                    src_ip = src.get("ip_or_cidr") or src.get("label", "any")
                    tgt_ip = tgt.get("ip_or_cidr") or tgt.get("label", "any")

                    # Generate Inbound on Target (One-Way or Bidirectional)
                    ports_str = ",".join(str(p) for p in allowed_ports)
                    rule_name = f"NRC-Rel-{rule_seq:03d}-{src['label'][:10]}-to-{tgt['label'][:10]}"

                    # Windows Syntax
                    win_cmd = (
                        f'netsh advfirewall firewall add rule name="{rule_name}" '
                        f'dir=in action=allow protocol={protocol.upper()} localport={ports_str} '
                        f'remoteip={src_ip} profile=any enable=yes'
                    )
                    if logging:
                        win_cmd += " description=\"NRC-Enforced;Logging=Active\""

                    # Linux nftables Syntax
                    nft_state = "ct state new,established " if stateful else ""
                    nft_log = 'log prefix "[NRC-ACCEPT] " ' if logging else ""
                    nft_cmd = (
                        f"nft add rule inet nrc_filter input "
                        f"ip saddr {src_ip} {protocol} dport {{ {ports_str} }} "
                        f"{nft_state}{nft_log}accept"
                    )

                    # Linux iptables Syntax
                    ipt_cmd = (
                        f"iptables -A INPUT -p {protocol} -s {src_ip} -m multiport --dports {ports_str} "
                        f"{'-m conntrack --ctstate NEW,ESTABLISHED ' if stateful else ''}"
                        f"-j ACCEPT"
                    )

                    # Ubuntu/Debian ufw Syntax
                    ufw_cmd = f"ufw allow from {src_ip} to any port {ports_str} proto {protocol} comment '{rule_name}'"

                    # pf (macOS / pfSense / OPNsense) Syntax
                    pf_cmd = (
                        f"pass in quick proto {protocol} from {src_ip} to {tgt_ip} port {{ {ports_str.replace(',', ' ')} }} "
                        f"{'flags S/SA keep state' if stateful else 'no state'}"
                    )

                    chosen_cmd = win_cmd
                    if provider == "nftables":
                        chosen_cmd = nft_cmd
                    elif provider == "iptables":
                        chosen_cmd = ipt_cmd
                    elif provider == "ufw":
                        chosen_cmd = ufw_cmd
                    elif provider in ["pf", "pfsense", "opnsense"]:
                        chosen_cmd = pf_cmd

                    raw_script_lines.append(f"# Relationship: {src['label']} -> {tgt['label']} ({protocol.upper()} {ports_str})")
                    if triggered_ports:
                        raw_script_lines.append(f"# [Triggered/Dynamic Ports: {', '.join(triggered_ports)}]")
                    raw_script_lines.append(chosen_cmd)

                    rule_entry = {
                        "id": f"rule_{rule_seq}",
                        "name": rule_name,
                        "relationship_id": rel.get("id"),
                        "source": src["label"],
                        "source_ip": src_ip,
                        "target": tgt["label"],
                        "target_ip": tgt_ip,
                        "protocol": protocol,
                        "ports": allowed_ports,
                        "triggered_ports": triggered_ports,
                        "direction": "inbound",
                        "action": "allow",
                        "native_command": chosen_cmd,
                        "notes": notes,
                    }
                    compiled_rules.append(rule_entry)
                    rule_seq += 1

                    # If bidirectional, synthesize return path rule
                    if direction == "bidirectional":
                        rev_rule_name = f"NRC-Rel-{rule_seq:03d}-{tgt['label'][:10]}-to-{src['label'][:10]}"
                        rev_win_cmd = (
                            f'netsh advfirewall firewall add rule name="{rev_rule_name}" '
                            f'dir=in action=allow protocol={protocol.upper()} localport={ports_str} '
                            f'remoteip={tgt_ip} profile=any enable=yes'
                        )
                        raw_script_lines.append(f"# Return Path (Bidirectional Trust): {tgt['label']} -> {src['label']}")
                        raw_script_lines.append(rev_win_cmd if provider == "windows_firewall" else chosen_cmd)

                        compiled_rules.append({
                            "id": f"rule_{rule_seq}",
                            "name": rev_rule_name,
                            "relationship_id": rel.get("id"),
                            "source": tgt["label"],
                            "source_ip": tgt_ip,
                            "target": src["label"],
                            "target_ip": src_ip,
                            "protocol": protocol,
                            "ports": allowed_ports,
                            "triggered_ports": triggered_ports,
                            "direction": "inbound",
                            "action": "allow",
                            "native_command": rev_win_cmd if provider == "windows_firewall" else chosen_cmd,
                            "notes": f"Bidirectional return trust for {rule_name}",
                        })
                        rule_seq += 1

                    raw_script_lines.append("")

        return {
            "provider": provider,
            "target_node_id": target_node_id,
            "total_rules": len(compiled_rules),
            "rules": compiled_rules,
            "script_content": "\n".join(raw_script_lines),
        }


class AIPolicyAssistant:
    """
    Translates natural-language intent expressions into first-class
    Network Relationship Canvas nodes and relationships.
    """

    @staticmethod
    def parse_intent(prompt: str, topology: Dict[str, Any]) -> Dict[str, Any]:
        """
        Parses intent strings such as:
          - 'Allow workstations to access web servers on HTTPS only'
          - 'Developers need SSH access to all Linux servers'
          - 'Allow finance laptops to access PostgreSQL database on port 5432'
          - 'Block all traffic between Guest Wi-Fi and Internal LAN'
        """
        prompt_lower = prompt.lower().strip()
        nodes = topology.get("nodes", [])
        groups = topology.get("groups", [])

        # Heuristic Port Detection
        ports = []
        if "https" in prompt_lower or "443" in prompt_lower:
            ports.append("443")
        if "http" in prompt_lower or "80" in prompt_lower:
            if "80" not in ports and "https" not in prompt_lower:
                ports.append("80")
            elif "http and https" in prompt_lower or "80 and 443" in prompt_lower or "web" in prompt_lower:
                ports.append("80")
                if "443" not in ports:
                    ports.append("443")
        if "ssh" in prompt_lower or "22" in prompt_lower:
            ports.append("22")
        if "dns" in prompt_lower or "53" in prompt_lower:
            ports.append("53")
        if "rtsp" in prompt_lower or "camera" in prompt_lower or "554" in prompt_lower:
            ports.append("554")
        if "postgres" in prompt_lower or "psql" in prompt_lower or "5432" in prompt_lower:
            ports.append("5432")
        if "mysql" in prompt_lower or "3306" in prompt_lower:
            ports.append("3306")
        if "rdp" in prompt_lower or "3389" in prompt_lower:
            ports.append("3389")

        # Explicit numeric port extraction fallback
        port_match = re.findall(r"\bport\s+(\d+)\b", prompt_lower)
        for pm in port_match:
            if pm not in ports:
                ports.append(pm)

        if not ports:
            ports = ["443"]  # Sensible default

        # Protocol Detection
        protocol = "tcp"
        if "udp" in prompt_lower or "dns" in prompt_lower:
            protocol = "udp"
        if "icmp" in prompt_lower or "ping" in prompt_lower:
            protocol = "icmp"

        # Direction Detection
        direction = "one_way"
        if "bidirectional" in prompt_lower or "mutual" in prompt_lower or "both ways" in prompt_lower:
            direction = "bidirectional"

        # Source and Target Identification
        source_candidate: Optional[Dict[str, Any]] = None
        target_candidate: Optional[Dict[str, Any]] = None

        # Check Groups First
        for g in groups:
            gname = g["name"].lower()
            if any(term in gname for term in ["workstation", "dev", "laptop", "client", "finance"]):
                if any(w in prompt_lower for w in ["workstation", "dev", "developer", "laptop", "client", "finance"]):
                    if not source_candidate:
                        source_candidate = {"id": g["id"], "label": g["name"], "is_group": True}
            if any(term in gname for term in ["server", "app", "web", "tier", "cluster"]):
                if any(w in prompt_lower for w in ["server", "web", "app", "application", "database", "postgres"]):
                    target_candidate = {"id": g["id"], "label": g["name"], "is_group": True}

        # Check Nodes Second
        for n in nodes:
            nlabel = n["label"].lower()
            if any(w in prompt_lower for w in ["win11", "workstation", "dev", "laptop"]):
                if "win11" in nlabel or "ws-" in nlabel:
                    if not source_candidate:
                        source_candidate = {"id": n["id"], "label": n["label"], "is_group": False}
            if any(w in prompt_lower for w in ["web", "nginx", "api"]):
                if "web" in nlabel or "nginx" in nlabel:
                    target_candidate = {"id": n["id"], "label": n["label"], "is_group": False}
            elif any(w in prompt_lower for w in ["db", "database", "postgres"]):
                if "db" in nlabel or "postgres" in nlabel:
                    target_candidate = {"id": n["id"], "label": n["label"], "is_group": False}
            elif any(w in prompt_lower for w in ["camera", "cam", "ptz", "surveillance"]):
                if "cam" in nlabel:
                    target_candidate = {"id": n["id"], "label": n["label"], "is_group": False}

        # Fallback to sensible nodes in topology if prompt is general
        if not source_candidate and len(nodes) > 0:
            source_candidate = {"id": nodes[0]["id"], "label": nodes[0]["label"], "is_group": False}
        if not target_candidate and len(nodes) > 1:
            target_candidate = {"id": nodes[1]["id"], "label": nodes[1]["label"], "is_group": False}

        proposed_relationship = {
            "source_node_id": source_candidate["id"] if source_candidate else "node_ws_win11",
            "source_label": source_candidate["label"] if source_candidate else "Workstations",
            "target_node_id": target_candidate["id"] if target_candidate else "node_srv_web",
            "target_label": target_candidate["label"] if target_candidate else "Application Tier",
            "direction": direction,
            "protocol": protocol,
            "allowed_ports": ports,
            "triggered_ports": ["1024-65535"] if "554" in ports else [],
            "is_stateful": True,
            "logging_enabled": True,
            "ids_enabled": True if "ssh" in prompt_lower or "22" in ports else False,
            "ai_notes": f"AI Intent Generated from: '{prompt}'",
            "traffic_status": "expected",
        }

        # Human-readable intent notation summary
        notation_arrow = "──" + ",".join(ports) + "──>" if direction == "one_way" else "<══" + ",".join(ports) + "══>"
        intent_visual = f"{proposed_relationship['source_label']} {notation_arrow} {proposed_relationship['target_label']}"

        return {
            "success": True,
            "prompt": prompt,
            "intent_visual": intent_visual,
            "proposed_relationship": proposed_relationship,
            "confidence_score": 0.94,
            "explanation": (
                f"Generated {direction.replace('_', ' ')} policy permitting {protocol.upper()} communication on port(s) "
                f"{', '.join(ports)} from {proposed_relationship['source_label']} to {proposed_relationship['target_label']}. "
                f"Strict zero-trust default deny is maintained for all unmentioned ports."
            ),
        }
